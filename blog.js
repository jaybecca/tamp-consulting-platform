/* TAMP Consulting Blog — standalone static-site functionality */
(function () {
  "use strict";

  function initBlog() {
    const posts = Array.isArray(window.hrBlogPosts) ? window.hrBlogPosts : [];

    const grid = document.getElementById("blogGrid");
    const searchInput = document.getElementById("blogSearch");
    const searchButton = document.getElementById("blogSearchButton");
    const clearButton = document.getElementById("blogClearSearch");
    const filters = document.getElementById("blogFilters");
    const resultsCount = document.getElementById("resultsCount");
    const featured = document.getElementById("featuredPost");

    const modal = document.getElementById("articleModal");
    const modalCategory = document.getElementById("modalCategory");
    const modalTitle = document.getElementById("modalTitle");
    const modalContent = document.getElementById("modalContent");
    const modalClose = document.getElementById("modalClose");

    if (!grid || !searchInput || !searchButton || !clearButton || !filters || !resultsCount || !featured || !modal) {
      console.error("TAMP Blog: required HTML elements were not found.");
      return;
    }

    const categories = ["All"].concat(
      Array.from(new Set(posts.map(function (post) {
        return post.category;
      }).filter(Boolean)))
    );

    let activeCategory = "All";
    let searchTerm = "";

    function escapeHTML(value) {
      return String(value == null ? "" : value).replace(/[&<>"']/g, function (char) {
        return {
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&#039;"
        }[char];
      });
    }

    function normalize(value) {
      return String(value == null ? "" : value)
        .toLowerCase()
        .replace(/\s+/g, " ")
        .trim();
    }

    function renderFilters() {
      filters.innerHTML = categories.map(function (category) {
        const selected = category === activeCategory ? " selected" : "";
        return '<option value="' + escapeHTML(category) + '"' + selected + '>' +
          escapeHTML(category === "All" ? "All topics" : category) +
          '</option>';
      }).join("");

      filters.value = activeCategory;
    }

    function getFilteredPosts() {
      const term = normalize(searchTerm);

      return posts.filter(function (post) {
        const categoryMatch =
          activeCategory === "All" || post.category === activeCategory;

        const searchableText = normalize([
          post.title,
          post.category,
          post.excerpt,
          post.content
        ].join(" "));

        const searchMatch = !term || searchableText.includes(term);
        return categoryMatch && searchMatch;
      });
    }

    function renderPosts() {
      const filtered = getFilteredPosts();

      resultsCount.textContent =
        "Showing " + filtered.length + " " +
        (filtered.length === 1 ? "article" : "articles");

      if (!filtered.length) {
        grid.innerHTML = `
          <div class="hr-no-results">
            <div class="hr-no-results-icon">⌕</div>
            <h3>No matching articles found.</h3>
            <p>Try another keyword or choose a different topic above.</p>
            <button type="button" class="hr-primary-btn" id="resetBlogFilters">
              Show all articles
            </button>
          </div>
        `;

        document.getElementById("resetBlogFilters").addEventListener("click", function () {
          searchTerm = "";
          searchInput.value = "";
          activeCategory = "All";
          renderFilters();
          renderPosts();
          searchInput.focus();
        });
        return;
      }

      grid.innerHTML = filtered.map(function (post, index) {
        return `
          <article class="hr-blog-card">
            <div class="hr-card-number">${String(index + 1).padStart(2, "0")}</div>
            <span class="hr-card-category">${escapeHTML(post.category)}</span>
            <h3>${escapeHTML(post.title)}</h3>
            <p>${escapeHTML(post.excerpt)}</p>

            <div class="hr-card-footer">
              <button type="button" class="read-article" data-id="${Number(post.id)}">
                Read article →
              </button>
              <span>TAMP CONSULTING</span>
            </div>
          </article>
        `;
      }).join("");

      grid.querySelectorAll(".read-article").forEach(function (button) {
        button.addEventListener("click", function () {
          openArticle(Number(this.dataset.id));
        });
      });
    }

    function renderFeatured() {
      const post = posts[0];
      if (!post) {
        featured.innerHTML = '<div class="hr-featured-copy"><p>No featured article is available.</p></div>';
        return;
      }

      featured.innerHTML = `
        <div class="hr-featured-copy">
          <span class="hr-category">${escapeHTML(post.category)}</span>
          <h2>${escapeHTML(post.title)}</h2>
          <p>${escapeHTML(post.excerpt)}</p>
          <button type="button" class="hr-read-btn" id="featuredRead">
            Read the story →
          </button>
        </div>

        <div class="hr-featured-art" aria-hidden="true">
          <div class="hr-art-circle">
            <div class="hr-person">●</div>
            <div class="hr-person p2">●</div>
            <div class="hr-person p3">●</div>
            <div class="hr-art-center">HR</div>
          </div>
        </div>
      `;

      document.getElementById("featuredRead").addEventListener("click", function () {
        openArticle(post.id);
      });
    }

    function openArticle(id) {
      const post = posts.find(function (item) {
        return Number(item.id) === Number(id);
      });

      if (!post) return;

      modalCategory.textContent = post.category || "";
      modalTitle.textContent = post.title || "";

      const paragraphs = String(post.content || "")
        .trim()
        .split(/\n\s*\n/)
        .map(function (paragraph) {
          return paragraph.trim();
        })
        .filter(Boolean);

      modalContent.innerHTML = paragraphs.map(function (paragraph) {
        return "<p>" + escapeHTML(paragraph).replace(/\n/g, "<br>") + "</p>";
      }).join("");

      modal.classList.add("is-open");
      modal.setAttribute("aria-hidden", "false");
      document.body.classList.add("modal-open");
      modalClose.focus();
    }

    function closeArticle() {
      modal.classList.remove("is-open");
      modal.setAttribute("aria-hidden", "true");
      document.body.classList.remove("modal-open");
    }

    function runSearch() {
      searchTerm = searchInput.value;
      renderPosts();
    }

    searchButton.addEventListener("click", runSearch);

    searchInput.addEventListener("input", function () {
      searchTerm = this.value;
      renderPosts();
    });

    searchInput.addEventListener("keydown", function (event) {
      if (event.key === "Enter") {
        event.preventDefault();
        runSearch();
      }
    });

    clearButton.addEventListener("click", function () {
      searchInput.value = "";
      searchTerm = "";
      renderPosts();
      searchInput.focus();
    });

    filters.addEventListener("change", function () {
      activeCategory = this.value;
      renderPosts();
    });

    modalClose.addEventListener("click", closeArticle);

    modal.addEventListener("click", function (event) {
      if (event.target === modal) closeArticle();
    });

    document.addEventListener("keydown", function (event) {
      if (event.key === "Escape" && modal.classList.contains("is-open")) {
        closeArticle();
      }
    });

    renderFeatured();
    renderFilters();
    renderPosts();

    const year = document.getElementById("currentYear");
    if (year) year.textContent = new Date().getFullYear();
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initBlog);
  } else {
    initBlog();
  }
})();
